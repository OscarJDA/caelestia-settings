"""Caelestia colour scheme / theming (E6)."""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import gi

gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")

from gi.repository import Adw, Gtk  # noqa: E402

from src.lang import t  # noqa: E402

SCHEME_STATE = Path.home() / ".local" / "state" / "caelestia" / "scheme.json"

SCHEMES = (
    "caelestia", "catppuccin", "darkgreen", "dracula", "everblush", "everforest",
    "gruvbox", "nord", "oldworld", "onedark", "rosepine", "shadotheme", "solarized",
    "tokyonight", "dynamic",
)
VARIANTS = (
    "tonalspot", "vibrant", "expressive", "fidelity", "fruitsalad",
    "monochrome", "neutral", "rainbow", "content",
)


def _read_state() -> dict:
    try:
        return json.loads(SCHEME_STATE.read_text())
    except (OSError, json.JSONDecodeError):
        return {}


def _scheme_flavours() -> dict[str, list[str]]:
    try:
        result = subprocess.run(
            ["caelestia", "scheme", "list"],
            capture_output=True,
            text=True,
            timeout=20,
        )
        data = json.loads(result.stdout) if result.returncode == 0 else {}
    except (OSError, subprocess.TimeoutExpired, json.JSONDecodeError):
        return {}
    flavours = {}
    for name, variants in data.items():
        if isinstance(variants, dict):
            flavours[name] = list(variants.keys())
    return flavours


class ThemingPage(Adw.PreferencesPage):
    def __init__(self, main_window):
        super().__init__()
        self.main_window = main_window
        self._state = _read_state()
        self._flavour_options = _scheme_flavours()
        self._flavour_values: list[str] = []
        self._build()
        self._refresh_preview()

    def _build(self) -> None:
        group = Adw.PreferencesGroup(
            title=t("Scheme"),
            description=t("Generated by the Caelestia CLI and applied to the shell, apps and Hyprland."),
        )

        self._name = Adw.ComboRow(title=t("Scheme"))
        self._name.set_model(Gtk.StringList.new(list(SCHEMES)))
        current = self._state.get("name", "caelestia")
        self._name.set_selected(SCHEMES.index(current) if current in SCHEMES else 0)
        self._name.connect("notify::selected", lambda *_: self._on_scheme_changed())
        group.add(self._name)

        self._flavour = Adw.ComboRow(title=t("Flavour"))
        self._set_flavour_options(self._state.get("flavour", ""))
        group.add(self._flavour)

        self._mode = Adw.ComboRow(title=t("Mode"))
        self._mode.set_model(Gtk.StringList.new([t("Dark"), t("Light")]))
        self._mode.set_selected(1 if self._state.get("mode") == "light" else 0)
        group.add(self._mode)

        self._variant = Adw.ComboRow(title=t("Variant"))
        self._variant.set_model(Gtk.StringList.new(list(VARIANTS)))
        variant = self._state.get("variant", "tonalspot")
        self._variant.set_selected(VARIANTS.index(variant) if variant in VARIANTS else 0)
        group.add(self._variant)

        row = Adw.ActionRow(title=t("Apply scheme"), subtitle=t("Runs caelestia scheme set"))
        self._apply_btn = Gtk.Button(label=t("Apply"))
        self._apply_btn.add_css_class("suggested-action")
        self._apply_btn.set_valign(Gtk.Align.CENTER)
        self._apply_btn.connect("clicked", lambda _b: self._apply())
        row.add_suffix(self._apply_btn)
        group.add(row)

        actions = Adw.ActionRow(title=t("Quick actions"))
        box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=6)
        box.set_valign(Gtk.Align.CENTER)
        self._random_btn = Gtk.Button(label=t("Random scheme"))
        self._random_btn.connect("clicked", lambda _b: self._run(["-r"]))
        self._dynamic_btn = Gtk.Button(label=t("From wallpaper"))
        self._dynamic_btn.connect("clicked", lambda _b: self._run(["-n", "dynamic"]))
        box.append(self._random_btn)
        box.append(self._dynamic_btn)
        actions.add_suffix(box)
        group.add(actions)
        self.add(group)

        palette_group = Adw.PreferencesGroup(title=t("Current palette"))
        self._palette_row = Adw.ActionRow(title=t("Colours"))
        self._palette = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=4)
        self._palette.set_valign(Gtk.Align.CENTER)
        self._palette_row.add_suffix(self._palette)
        palette_group.add(self._palette_row)
        self.add(palette_group)

        if not shutil.which("caelestia"):
            self._apply_btn.set_sensitive(False)
            self._random_btn.set_sensitive(False)
            self._dynamic_btn.set_sensitive(False)

    def _on_scheme_changed(self) -> None:
        self._set_flavour_options(None)

    def _set_flavour_options(self, preferred: str | None) -> None:
        selected = self._name.get_selected() if hasattr(self, "_name") else 0
        if not (0 <= selected < len(SCHEMES)):
            selected = 0
        name = SCHEMES[selected]
        values = self._flavour_options.get(name) or [preferred or "default"]
        self._flavour_values = values
        self._flavour.set_model(Gtk.StringList.new(values))
        try:
            index = values.index(preferred) if preferred else 0
        except ValueError:
            index = 0
        self._flavour.set_selected(index)

    def _refresh_preview(self) -> None:
        self._state = _read_state()
        colours = self._state.get("colours", {})
        while (child := self._palette.get_first_child()) is not None:
            self._palette.remove(child)
        for key in ("primary", "secondary", "tertiary", "surfaceContainer", "background", "outline"):
            value = colours.get(key)
            if not value:
                continue
            swatch = Gtk.Box()
            swatch.set_size_request(24, 24)
            swatch.set_tooltip_text(f"{key}: #{value}")
            provider = Gtk.CssProvider()
            try:
                provider.load_from_data(
                    f".swatch-{key} {{ background-color: #{value}; border-radius: 6px; }}".encode()
                )
                swatch.add_css_class(f"swatch-{key}")
                swatch.get_style_context().add_provider(
                    provider, Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION
                )
            except Exception:
                pass
            self._palette.append(swatch)
        self._palette_row.set_subtitle(
            f"{self._state.get('name', '?')} · {self._state.get('flavour', '?')} · "
            f"{self._state.get('mode', '?')} · {self._state.get('variant', '?')}"
        )
        name = self._state.get("name")
        if hasattr(self, "_name") and name in SCHEMES:
            self._name.set_selected(SCHEMES.index(name))
            self._set_flavour_options(self._state.get("flavour"))

    def _apply(self) -> None:
        name = SCHEMES[self._name.get_selected()] if 0 <= self._name.get_selected() < len(SCHEMES) else "caelestia"
        mode = "light" if self._mode.get_selected() == 1 else "dark"
        variant = VARIANTS[self._variant.get_selected()] if 0 <= self._variant.get_selected() < len(VARIANTS) else "tonalspot"
        args = ["-n", name, "-m", mode, "-v", variant]
        selected = self._flavour.get_selected()
        if 0 <= selected < len(self._flavour_values):
            args += ["-f", self._flavour_values[selected]]
        self._run(args)

    def _run(self, args: list[str]) -> None:
        try:
            result = subprocess.run(
                ["caelestia", "scheme", "set", *args],
                capture_output=True,
                text=True,
                timeout=90,
            )
            if result.returncode == 0:
                self.main_window.add_toast(Adw.Toast.new(t("Colour scheme updated")))
                self._refresh_preview()
            else:
                message = (result.stderr or result.stdout or "scheme update failed").strip().splitlines()
                self.main_window.add_toast(Adw.Toast.new(message[0] if message else t("Scheme update failed")))
        except (OSError, subprocess.TimeoutExpired) as exc:
            self.main_window.add_toast(Adw.Toast.new(t("Scheme update failed: {error}").format(error=exc)))
