"""SDDM login theme template editor (D9).

Only the non-colour settings of Caelestia's ``sddm-theme.conf`` template are
exposed; the colour placeholders are regenerated by Caelestia itself.
"""

from __future__ import annotations

import copy
import re
from pathlib import Path

from src.safe_io import HISTORY, atomic_write_text
from src.settings_engine import SettingsPage
from src.settings_schema import LOGIN_THEME_SPEC

TEMPLATE = Path.home() / ".config" / "caelestia" / "templates" / "sddm-theme.conf"

_BOOL_TRUE = {"true", "yes", "1", "on"}
_MISSING = object()


class KeyValueBackend:
    """Read/write ``key=value`` lines while preserving comments and ordering."""

    def __init__(self, path: Path) -> None:
        self.path = path

    def available(self, key: str) -> bool:
        return True

    def _read(self) -> str:
        try:
            return self.path.read_text(encoding="utf-8")
        except OSError:
            return ""

    def get(self, key: str, kind: str | None = None, default=None):
        match = re.search(rf"^\s*{re.escape(key)}\s*=\s*(.*?)\s*$", self._read(), re.MULTILINE)
        if not match:
            return default
        raw = match.group(1).strip().strip('"')
        if kind == "bool":
            return raw.lower() in _BOOL_TRUE
        if kind == "int":
            try:
                return int(raw)
            except ValueError:
                return default
        if kind == "float":
            try:
                return float(raw)
            except ValueError:
                return default
        return raw

    def set(self, key: str, value, label: str | None = None, record: bool = True) -> bool:
        text = self._read()
        old = self.get(key, default=_MISSING)
        if old is not _MISSING and old == value:
            return True
        old_snapshot = copy.deepcopy(old) if old is not _MISSING else _MISSING
        rendered = "true" if value is True else ("false" if value is False else str(value))
        pattern = re.compile(rf"^(\s*{re.escape(key)}\s*=\s*).*$", re.MULTILINE)
        if pattern.search(text):
            text = pattern.sub(lambda m: m.group(1) + rendered, text, count=1)
        else:
            text = text.rstrip() + f"\n{key}={rendered}\n"
        atomic_write_text(self.path, text)

        if record:
            def undo() -> None:
                current = self.path.read_text(encoding="utf-8") if self.path.exists() else ""
                if old_snapshot is _MISSING:
                    current = re.sub(rf"^\s*{re.escape(key)}\s*=.*\n?", "", current, flags=re.MULTILINE)
                else:
                    old_rendered = "true" if old_snapshot is True else (
                        "false" if old_snapshot is False else str(old_snapshot)
                    )
                    current = re.sub(
                        rf"^(\s*{re.escape(key)}\s*=\s*).*$",
                        lambda m: m.group(1) + old_rendered,
                        current,
                        count=1,
                        flags=re.MULTILINE,
                    )
                atomic_write_text(self.path, current)

            def redo() -> None:
                current = self.path.read_text(encoding="utf-8") if self.path.exists() else ""
                if re.search(rf"^\s*{re.escape(key)}\s*=", current, re.MULTILINE):
                    current = re.sub(
                        rf"^(\s*{re.escape(key)}\s*=\s*).*$",
                        lambda m: m.group(1) + rendered,
                        current,
                        count=1,
                        flags=re.MULTILINE,
                    )
                else:
                    current = current.rstrip() + f"\n{key}={rendered}\n"
                atomic_write_text(self.path, current)

            HISTORY.push(label or f"{key} = {rendered}", undo, redo)
        return True


class LoginThemePage(SettingsPage):
    def __init__(self, main_window):
        super().__init__(main_window, LOGIN_THEME_SPEC, KeyValueBackend(TEMPLATE))
